// Compiles runtime/runtime.ts into src/runtime.generated.ts: one minified IIFE string
// plus its SHA-256, which renderPage() puts in the page's Content-Security-Policy.
//   node scripts/build-runtime.ts          (pnpm gen)
// Also imported by the studio's Vite config, which rebuilds it when the runtime changes.

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const RUNTIME_ENTRY = join(root, "runtime", "runtime.ts");
export const RUNTIME_OUT = join(root, "src", "runtime.generated.ts");
export const RUNTIME_BUDGET = 5120;

export interface RuntimeBuild { code: string; sha256: string; bytes: number; written: boolean }

export async function buildRuntime({ write = true }: { write?: boolean } = {}): Promise<RuntimeBuild> {
  const result = await build({
    entryPoints: [RUNTIME_ENTRY],
    bundle: true,
    write: false,
    minify: true,
    format: "iife",
    target: ["es2020"],
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
  });
  const code = result.outputFiles[0]!.text.trim();
  if (/<\/script|<!--/i.test(code)) throw new Error("The runtime must not contain </script or <!-- (it is inlined into HTML).");
  if (code.length > RUNTIME_BUDGET) throw new Error(`The runtime is ${code.length} bytes; the budget is ${RUNTIME_BUDGET}.`);
  const sha256 = createHash("sha256").update(code, "utf8").digest("base64");
  const file =
    `// Generated by scripts/build-runtime.ts from runtime/runtime.ts. Do not edit; run \`pnpm gen\`.\n` +
    `export const RUNTIME_JS = ${JSON.stringify(code)};\n` +
    `export const RUNTIME_SHA256 = ${JSON.stringify(sha256)};\n`;
  const current = existsSync(RUNTIME_OUT) ? readFileSync(RUNTIME_OUT, "utf8") : "";
  const written = write && current !== file;
  if (written) writeFileSync(RUNTIME_OUT, file);
  return { code, sha256, bytes: code.length, written };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await buildRuntime();
  console.log(`runtime: ${r.bytes} B minified, sha256-${r.sha256}${r.written ? " (updated)" : " (unchanged)"}`);
}
